async function main() {
  const forceContentSeed = process.env.FORCE_CONTENT_SEED === "true";
  const email = process.env.ADMIN_EMAIL || "admin@sepidar.local";
  const password = process.env.ADMIN_PASSWORD;
  if (!password || password.length < 12) {
    throw new Error("ADMIN_PASSWORD must be set and contain at least 12 characters");
  }

  await prisma.user.upsert({
    where: { email },
    update: { active: true, role: UserRole.ADMIN },
    create: {
      name: "مدیر سیستم",
      email,
      passwordHash: await hash(password, 12),
      role: UserRole.ADMIN,
    },
  });

  for (const service of services) {
    await prisma.service.upsert({
      where: { slug: service.slug },
      update: forceContentSeed ? service : {},
      create: service,
    });
  }
  for (const faq of faqs) {
    const existing = await prisma.faq.findFirst({ where: { order: faq.order } });
    if (existing) {
      if (forceContentSeed) await prisma.faq.update({ where: { id: existing.id }, data: { ...faq, active: true } });
    } else {
      await prisma.faq.create({ data: faq });
    }
  }
  for (const [key, label, value, group] of content) {
    await prisma.contentEntry.upsert({
      where: { key },
      update: forceContentSeed ? { label, value, group } : {},
      create: { key, label, value, group },
    });
  }
  const settings = {
    centerName: "مرکز ترک اعتیاد طلوع خورشید",
    phone: "09357238914",
    mobile: "09357238914",
    email: "",
    address: "نشانی دقیق مرکز پیش از مراجعه تلفنی اعلام می‌شود",
  };
  await prisma.siteSetting.upsert({ where: { id: 1 }, update: forceContentSeed ? settings : {}, create: { id: 1, ...settings } });
}

main()
  .then(() => console.log("Database seeded successfully."))
  .finally(() => prisma.$disconnect());
